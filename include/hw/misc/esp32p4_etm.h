/*
 * How a peripheral connects its events and tasks
 * ==============================================
 *
 * Every event and task has the number that selects it in
 * SOC_ETM_CHn_EVT_ID and SOC_ETM_CHn_TASK_ID: ESP32P4_ETM_<name> below,
 * the names and numbers of ESP-IDF's soc_etm_source.h for the P4 (TRM
 * tables 14.3-1 and 14.3-2 list most of them, calling the PDMA ones
 * GDMA_*). Number 0 selects nothing.
 *
 * A peripheral model has a line of a named GPIO output, by convention
 * "etm-event", for each ETM event it generates, which it pulses
 * (qemu_irq_pulse()) as the event happens, and a line of a named GPIO
 * input, by convention "etm-task", for each ETM task it takes, which it
 * acts on as the line rises. Whether it generates an event or takes a task
 * at all, its own ETM enables (TIMG_ETM_EN, SYSTIMER_ETM_EN, GPIO_EXT's
 * ETM configuration, ...) decide inside the model; the ETM only maps
 * events to tasks. The machine (hw/riscv/esp32p4.c, esp32p4_init_etm())
 * connects each line with one call, in a loop where a block's IDs run in
 * step with its lines:
 *
 *   for (n = 0; n < 3; n++) {
 *       esp32p4_etm_connect_event(etm, ESP32P4_ETM_MCPWM0_EVT_TIMER0_STOP
 *                                      + n, DEVICE(&s->mcpwm[0]),
 *                                 "etm-event", n);
 *   }
 *   esp32p4_etm_connect_task(etm, ESP32P4_ETM_I2S0_TASK_START_RX,
 *                            DEVICE(&s->i2s[0]), "etm-task", 0);
 *
 * Each event and each task is connected once. An event no modelled block
 * generates never comes; a task no modelled block takes is generated all
 * the same, its TASK_ST bit set, with nothing to act on it. An event that
 * is every edge of a clock, as RTC_EVT_TICK is every count of the RTC
 * timer, comes in as that clock instead ("rtc-evt-tick"), so that it costs
 * nothing while no channel maps it.
 *
 * Inputs and outputs:
 *
 *   - Clock input "clk": the ETM's SYS_CLK (ETM_SYS_CLK_EN's gate), in
 *     whose cycles it receives events and generates tasks; while it is
 *     stopped, events are lost.
 *   - Clock input "rtc-evt-tick": the RTC timer's counting clock, each of
 *     whose edges is RTC_EVT_TICK.
 *   - Named GPIO input "event", ESP32P4_ETM_EVENTS lines: line n is event
 *     n, a pulse as it happens (line 0 is unused).
 *   - Named GPIO output "task", ESP32P4_ETM_TASKS lines: line n is task n,
 *     pulsed as the ETM generates it (line 0 is unused).
 *   - Named GPIO input "reset": RST_EN_ETM, high while the block is held
 *     in reset. The machine maps the registers behind ETM_APB_CLK alone.
 */
#define ESP32P4_ETM_EVENT       "event"
#define ESP32P4_ETM_TASK        "task"
#define ESP32P4_ETM_RESET       "reset"

