#define ESP32P4_ETM_EVT_WORDS   DIV_ROUND_UP(ESP32P4_ETM_EVENTS - 1, 32)
#define ESP32P4_ETM_TASK_WORDS  DIV_ROUND_UP(ESP32P4_ETM_TASKS - 1, 32)

struct ESP32P4EtmState {
    SysBusDevice parent_obj;

    MemoryRegion iomem;
    Clock *clk;
    Clock *rtc_tick;
    qemu_irq task[ESP32P4_ETM_TASKS];
    QEMUTimer tick_timer;

    bool in_reset;
    /* CH_ENA_AD1:CH_ENA_AD0, a bit per channel. */
    uint64_t ch_ena;
    uint8_t evt_id[ESP32P4_ETM_CHANNELS];
    uint8_t task_id[ESP32P4_ETM_CHANNELS];
    /* EVT_STn and TASK_STn: bit id - 1 for event or task id. */
    uint32_t evt_st[ESP32P4_ETM_EVT_WORDS];
    uint32_t task_st[ESP32P4_ETM_TASK_WORDS];
    uint32_t clk_en;
    uint32_t date;

    /*
     * The time SYS_CLK last changed, from which its cycles are counted,
     * and the time each event was last received and each task last
     * generated, INT64_MIN for never: once in a cycle each.
     */
    int64_t clk_ns;
    int64_t evt_ns[ESP32P4_ETM_EVENTS];
    int64_t task_ns[ESP32P4_ETM_TASKS];

    /*
     * RTC_EVT_TICK: the edges of "rtc-evt-tick" since it last changed, at
     * @tick_ns, accounted for up to @tick_seen.
     */
    int64_t tick_ns;
    uint64_t tick_seen;

    /* Which events and tasks the machine has connected. */
    DECLARE_BITMAP(evt_wired, ESP32P4_ETM_EVENTS);
    DECLARE_BITMAP(task_wired, ESP32P4_ETM_TASKS);
};

